"""Excel (.xlsx) and CSV export.

The workbook is meant to be *used*, not just read:
  Summary        account details, totals, reconciliation checks, native charts
  Transactions   every row, Indian number format, frozen header, filters, a
                 category drop-down (data validation) so users can recategorise
                 in Excel, review / mismatch rows highlighted
  Categories     spend and income per category (SUMIFS formulas over Transactions,
                 so edits in Excel flow through)
  Monthly        inflow / outflow / net per month with a column chart
  Recurring      detected subscriptions / EMIs / salary
  Validation     integrity checks and every flagged row with the reason
"""
from __future__ import annotations

import csv
import io
from datetime import date, datetime
from typing import Iterable

import xlsxwriter

from ..classify import categories as C

INR = '[>=10000000]"₹"##\\,##\\,##\\,##0.00;[>=100000]"₹"##\\,##\\,##0.00;"₹"##,##0.00'
INR_PLAIN = '[>=10000000]##\\,##\\,##\\,##0.00;[>=100000]##\\,##\\,##0.00;##,##0.00'

TXN_COLUMNS = [
    ("Date", 12), ("Value Date", 12), ("Description", 52), ("Reference", 20), ("Debit", 14), ("Credit", 14),
    ("Balance", 15), ("Category", 24), ("Category Group", 12), ("Confidence", 11), ("Classified By", 13),
    ("Merchant / Counterparty", 26), ("Channel", 10), ("Recurring", 12), ("Self Transfer", 11),
    ("Reconciliation", 14), ("Needs Review", 12), ("Notes", 48), ("Statement", 22), ("Page", 6),
]

METHOD_LABEL = {"rule": "Rule", "merchant": "Merchant list", "ml": "ML model", "rule+ml": "Rule + ML",
                "merchant+ml": "Merchant + ML", "channel": "Channel rule", "learned": "Your rule", "user": "You",
                "fallback": "Fallback"}


def _d(v) -> date | None:
    if isinstance(v, date):
        return v
    if isinstance(v, str) and v:
        try:
            return date.fromisoformat(v)
        except ValueError:
            return None
    return None


def merge_transactions(statements: list[dict]) -> tuple[list[dict], int]:
    """Combine statements; drop rows repeated across overlapping statements of the same account."""
    seen: set[tuple] = set()
    out: list[dict] = []
    dupes = 0
    for s in statements:
        acct = s.get("account_key") or s["id"]
        for t in s["transactions"]:
            key = (acct, t.get("date"), round(t.get("debit") or 0, 2), round(t.get("credit") or 0, 2),
                   t.get("balance"), (t.get("description") or "")[:40])
            if len(statements) > 1 and t.get("balance") is not None and key in seen:
                dupes += 1
                continue
            seen.add(key)
            out.append({**t, "_statement": s.get("filename", s["id"]), "_stype": s.get("statement_type")})
    out.sort(key=lambda t: (t.get("date") or "", t["_statement"], t["idx"]))
    return out, dupes


def _row_values(t: dict, recurring_labels: dict[str, str]) -> list:
    cat = C.BY_ID.get(t["category"], C.BY_ID["other"])
    notes = list(t.get("notes") or [])
    if t.get("user_note"):
        notes.insert(0, f"Note: {t['user_note']}")
    if t.get("explanation"):
        notes.append(f"Why: {t['explanation']}")
    return [
        _d(t.get("date")), _d(t.get("value_date")), t.get("description") or "", t.get("reference") or "",
        t.get("debit"), t.get("credit"), t.get("balance"), cat.name, cat.kind.title(),
        t.get("confidence"), METHOD_LABEL.get(t.get("method"), t.get("method") or ""),
        t.get("merchant") or t.get("counterparty") or "", t.get("channel") or "",
        recurring_labels.get(t.get("recurring_id") or "", ""), "Yes" if t.get("self_transfer") else "",
        (t.get("recon_status") or "").title(), "Yes" if t.get("needs_review") and not t.get("reviewed") else "",
        " | ".join(notes), t.get("_statement", ""), (t.get("page") or 0) + 1,
    ]


def to_xlsx(statements: list[dict]) -> bytes:
    txns, dupes = merge_transactions(statements)
    buf = io.BytesIO()
    wb = xlsxwriter.Workbook(buf, {"in_memory": True, "default_date_format": "dd-mmm-yyyy"})
    wb.set_properties({"title": "Bank statement export", "author": "Befree Statement Studio",
                       "comments": "Generated by Befree Statement Studio"})

    ink, muted, accent = "#0F172A", "#64748B", "#5B5BD6"
    f = {
        "title": wb.add_format({"bold": True, "font_size": 18, "font_color": ink}),
        "subtitle": wb.add_format({"font_size": 10, "font_color": muted}),
        "h": wb.add_format({"bold": True, "font_color": "#FFFFFF", "bg_color": accent, "border": 0, "valign": "vcenter",
                            "text_wrap": True}),
        "label": wb.add_format({"font_color": muted}),
        "value": wb.add_format({"bold": True, "font_color": ink}),
        "money": wb.add_format({"num_format": INR_PLAIN}),
        "money_b": wb.add_format({"num_format": INR, "bold": True, "font_size": 13}),
        "date": wb.add_format({"num_format": "dd-mmm-yyyy"}),
        "pct": wb.add_format({"num_format": "0%"}),
        "wrap": wb.add_format({"text_wrap": True, "valign": "top"}),
        "section": wb.add_format({"bold": True, "font_size": 12, "font_color": accent, "bottom": 1, "bottom_color": "#E2E8F0"}),
        "pass": wb.add_format({"font_color": "#047857", "bold": True}),
        "fail": wb.add_format({"font_color": "#B91C1C", "bold": True}),
        "warn": wb.add_format({"font_color": "#B45309", "bold": True}),
        "skip": wb.add_format({"font_color": muted}),
        "review_row": wb.add_format({"bg_color": "#FFF7E6"}),
        "mismatch_row": wb.add_format({"bg_color": "#FDECEC"}),
    }

    # sheets are created in display order up front, then filled
    sm = wb.add_worksheet("Summary")
    ws = wb.add_worksheet("Transactions")
    wc = wb.add_worksheet("Categories")
    wm = wb.add_worksheet("Monthly")
    wr = wb.add_worksheet("Recurring")
    wv = wb.add_worksheet("Validation")
    lists = wb.add_worksheet("Lists")

    # ---------------- Transactions
    recurring_labels = {}
    for s in statements:
        for g in s.get("recurring") or []:
            recurring_labels[g["id"]] = g["cadence"].title()
    ws.set_row(0, 30)
    for i, (name, width) in enumerate(TXN_COLUMNS):
        ws.write(0, i, name, f["h"])
        ws.set_column(i, i, width)
    for r, t in enumerate(txns, start=1):
        for c, v in enumerate(_row_values(t, recurring_labels)):
            if v is None or v == "":
                ws.write_blank(r, c, None)
            elif c in (0, 1):
                ws.write_datetime(r, c, datetime(v.year, v.month, v.day), f["date"])
            elif c in (4, 5, 6):
                ws.write_number(r, c, v, f["money"])
            elif c == 9:
                ws.write_number(r, c, v, f["pct"])
            elif c == 19:
                ws.write_number(r, c, v)
            else:
                ws.write_string(r, c, str(v))
    last = len(txns)
    if last:
        ws.autofilter(0, 0, last, len(TXN_COLUMNS) - 1)
        ws.data_validation(1, 7, last, 7, {"validate": "list", "source": "=Lists!$A$1:$A$%d" % len(C.CATEGORIES),
                                           "error_title": "Unknown category", "error_message": "Pick a category from the list."})
        ws.conditional_format(1, 0, last, len(TXN_COLUMNS) - 1, {"type": "formula", "criteria": "=$P2=\"Mismatch\"",
                                                                  "format": f["mismatch_row"]})
        ws.conditional_format(1, 0, last, len(TXN_COLUMNS) - 1, {"type": "formula", "criteria": "=$Q2=\"Yes\"",
                                                                  "format": f["review_row"]})
    ws.freeze_panes(1, 3)

    for i, cat in enumerate(C.CATEGORIES):
        lists.write(i, 0, cat.name)
        lists.write(i, 1, cat.kind.title())
    lists.hide()

    # ---------------- Categories (formulas so Excel edits flow through)
    wc.write_row(0, 0, ["Category", "Group", "Debits", "Credits", "Transactions", "Share of spend"], f["h"])
    wc.set_column(0, 0, 30)
    wc.set_column(1, 1, 12)
    wc.set_column(2, 3, 16)
    wc.set_column(4, 5, 14)
    used = [c for c in C.CATEGORIES if any(t["category"] == c.id for t in txns)]
    n_rows = max(1, last)
    spend_cells = []
    for i, cat in enumerate(used, start=1):
        rng = f"Transactions!$H$2:$H${n_rows + 1}"
        wc.write(i, 0, cat.name)
        wc.write(i, 1, cat.kind.title())
        wc.write_formula(i, 2, f'=SUMIFS(Transactions!$E$2:$E${n_rows + 1},{rng},A{i + 1})', f["money"])
        wc.write_formula(i, 3, f'=SUMIFS(Transactions!$F$2:$F${n_rows + 1},{rng},A{i + 1})', f["money"])
        wc.write_formula(i, 4, f'=COUNTIFS({rng},A{i + 1})')
        if cat.kind == "expense":
            spend_cells.append(i + 1)
    total_spend = "+".join(f"C{r}" for r in spend_cells) or "1"
    for i, cat in enumerate(used, start=1):
        if cat.kind == "expense":
            wc.write_formula(i, 5, f"=IFERROR(C{i + 1}/({total_spend}),0)", f["pct"])
    if spend_cells:
        pie = wb.add_chart({"type": "doughnut"})
        pie.add_series({"name": "Spend by category",
                        "categories": ["Categories", spend_cells[0] - 1, 0, spend_cells[-1] - 1, 0],
                        "values": ["Categories", spend_cells[0] - 1, 2, spend_cells[-1] - 1, 2]})
        pie.set_title({"name": "Spend by category"})
        pie.set_hole_size(55)
        pie.set_size({"width": 560, "height": 360})
        wc.insert_chart("H2", pie)

    # ---------------- Monthly
    wm.write_row(0, 0, ["Month", "Inflow", "Outflow", "Net"], f["h"])
    wm.set_column(0, 0, 12)
    wm.set_column(1, 3, 16)
    months = sorted({(t.get("date") or "")[:7] for t in txns if t.get("date")})
    for i, m in enumerate(months, start=1):
        wm.write(i, 0, m)
        wm.write_formula(i, 1, f'=SUMPRODUCT((TEXT(Transactions!$A$2:$A${n_rows + 1},"yyyy-mm")=A{i + 1})*Transactions!$F$2:$F${n_rows + 1})', f["money"])
        wm.write_formula(i, 2, f'=SUMPRODUCT((TEXT(Transactions!$A$2:$A${n_rows + 1},"yyyy-mm")=A{i + 1})*Transactions!$E$2:$E${n_rows + 1})', f["money"])
        wm.write_formula(i, 3, f"=B{i + 1}-C{i + 1}", f["money"])
    if months:
        col = wb.add_chart({"type": "column"})
        col.add_series({"name": "Inflow", "categories": ["Monthly", 1, 0, len(months), 0],
                        "values": ["Monthly", 1, 1, len(months), 1], "fill": {"color": "#10B981"}})
        col.add_series({"name": "Outflow", "categories": ["Monthly", 1, 0, len(months), 0],
                        "values": ["Monthly", 1, 2, len(months), 2], "fill": {"color": "#F43F5E"}})
        col.set_title({"name": "Monthly cash flow"})
        col.set_size({"width": 640, "height": 340})
        wm.insert_chart("F2", col)

    # ---------------- Summary (first tab)
    sm.activate()
    sm.set_column(0, 0, 30)
    sm.set_column(1, 1, 44)
    sm.set_column(2, 2, 4)
    sm.set_column(3, 4, 22)
    sm.write(0, 0, "Statement summary", f["title"])
    sm.write(1, 0, f"Exported {datetime.now():%d %b %Y, %H:%M} · {len(statements)} statement(s) · {last} transactions"
             + (f" · {dupes} duplicate rows from overlapping statements removed" if dupes else ""), f["subtitle"])
    row = 3
    for s in statements:
        meta = s.get("meta") or {}
        sm.write(row, 0, s.get("filename") or s["id"], f["section"])
        sm.write(row, 1, "", f["section"])
        row += 1
        fields = [("Bank", meta.get("bank_name")), ("Account holder", meta.get("account_holder")),
                  ("Statement type", "Credit card" if s.get("statement_type") == "credit_card" else "Bank account"),
                  ("Account number", meta.get("account_number")), ("Card number", meta.get("card_number")),
                  ("IFSC", meta.get("ifsc")), ("Branch", meta.get("branch")), ("Customer ID", meta.get("customer_id")),
                  ("Period", f"{meta.get('period_from') or '?'} → {meta.get('period_to') or '?'}"),
                  ("Source PDF", f"{s.get('document_type', '')} · {s.get('page_count') or '?'} pages")]
        for k, v in fields:
            if v:
                sm.write(row, 0, k, f["label"])
                sm.write(row, 1, str(v), f["value"])
                row += 1
        recon = s.get("recon") or {}
        for k, key in (("Opening balance", "opening_balance"), ("Closing balance", "closing_balance"),
                       ("Total debits", "total_debits"), ("Total credits", "total_credits")):
            if recon.get(key) is not None:
                sm.write(row, 0, k, f["label"])
                sm.write_number(row, 1, recon[key], f["money_b"])
                row += 1
        if recon.get("integrity_score") is not None:
            sm.write(row, 0, "Reconciliation score", f["label"])
            sm.write(row, 1, f"{recon['integrity_score']:.1f} / 100", f["value"])
            row += 1
        for chk in recon.get("checks", []):
            sm.write(row, 0, chk["name"], f["label"])
            sm.write(row, 1, f"{chk['status'].upper()} — {chk['detail']}", f.get(chk["status"], f["skip"]))
            row += 1
        row += 1

    # ---------------- Recurring
    wr.write_row(0, 0, ["Payee", "Category", "Direction", "Cadence", "Average amount", "Occurrences", "Last", "Next expected"], f["h"])
    wr.set_column(0, 0, 30)
    wr.set_column(1, 1, 24)
    wr.set_column(2, 3, 12)
    wr.set_column(4, 4, 16)
    wr.set_column(5, 7, 14)
    r = 1
    for s in statements:
        for g in s.get("recurring") or []:
            wr.write_row(r, 0, [g["label"], C.name(g["category"]), g["direction"].title(), g["cadence"].title()])
            wr.write_number(r, 4, g["average_amount"], f["money"])
            wr.write_number(r, 5, g["count"])
            wr.write(r, 6, g["last_date"])
            wr.write(r, 7, g.get("next_expected") or "")
            r += 1
    if r == 1:
        wr.write(1, 0, "No recurring payments detected in this period.", f["label"])

    # ---------------- Validation
    wv.write_row(0, 0, ["Date", "Description", "Debit", "Credit", "Balance", "Status", "Flags", "Details"], f["h"])
    wv.set_column(0, 0, 12)
    wv.set_column(1, 1, 50)
    wv.set_column(2, 4, 14)
    wv.set_column(5, 6, 20)
    wv.set_column(7, 7, 70)
    r = 1
    for t in txns:
        if not t.get("flags") and t.get("recon_status") != "mismatch":
            continue
        d = _d(t.get("date"))
        if d:
            wv.write_datetime(r, 0, datetime(d.year, d.month, d.day), f["date"])
        wv.write(r, 1, t.get("description") or "")
        for c, k in ((2, "debit"), (3, "credit"), (4, "balance")):
            if t.get(k) is not None:
                wv.write_number(r, c, t[k], f["money"])
        wv.write(r, 5, (t.get("recon_status") or "").title())
        wv.write(r, 6, ", ".join(t.get("flags") or []))
        wv.write(r, 7, " ".join(t.get("notes") or []), f["wrap"])
        r += 1
    if r == 1:
        wv.write(1, 1, "No issues found: every row reconciles.", f["pass"])

    wb.close()
    return buf.getvalue()


CSV_HEADER = ["date", "value_date", "description", "reference", "debit", "credit", "balance", "category",
              "category_group", "confidence", "classified_by", "merchant_or_counterparty", "channel", "self_transfer",
              "reconciliation", "needs_review", "notes", "statement", "page"]


def to_csv(statements: list[dict]) -> bytes:
    txns, _ = merge_transactions(statements)
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow(CSV_HEADER)
    for t in txns:
        cat = C.BY_ID.get(t["category"], C.BY_ID["other"])
        w.writerow([
            t.get("date") or "", t.get("value_date") or "", t.get("description") or "", t.get("reference") or "",
            "" if t.get("debit") is None else f"{t['debit']:.2f}", "" if t.get("credit") is None else f"{t['credit']:.2f}",
            "" if t.get("balance") is None else f"{t['balance']:.2f}", cat.name, cat.kind,
            "" if t.get("confidence") is None else f"{t['confidence']:.2f}", METHOD_LABEL.get(t.get("method"), t.get("method") or ""),
            t.get("merchant") or t.get("counterparty") or "", t.get("channel") or "", "yes" if t.get("self_transfer") else "",
            t.get("recon_status") or "", "yes" if t.get("needs_review") and not t.get("reviewed") else "",
            " | ".join(t.get("notes") or []), t.get("_statement", ""), (t.get("page") or 0) + 1,
        ])
    # UTF-8 BOM so Excel opens ₹ and Indian names correctly
    return ("﻿" + out.getvalue()).encode("utf-8")


def filename_for(statements: Iterable[dict], ext: str) -> str:
    sts = list(statements)
    if len(sts) == 1:
        meta = sts[0].get("meta") or {}
        bank = (meta.get("bank_name") or "statement").replace(" ", "_")
        num = (meta.get("account_number") or meta.get("card_number") or "").replace(" ", "")[-4:]
        period = meta.get("period_to") or ""
        return f"{bank}{'_' + num if num else ''}{'_' + period if period else ''}.{ext}"
    return f"statements_combined_{len(sts)}.{ext}"
